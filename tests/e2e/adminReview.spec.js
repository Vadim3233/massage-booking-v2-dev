test('lost response after a committed transfer is safely retried with the same command key', async ({ page }) => {
  await f.authorize(); await login(page, `/admin/bookings/${f.bookings[0].id}`)
  const keys = []
  page.on('request', r => { if (r.url().endsWith('/rpc/admin_verify_bank_transfer')) keys.push(r.postDataJSON().p_request_id) })
  await page.route('**/rpc/admin_verify_bank_transfer', async route => {
    const response = await route.fetch()
    expect(response.ok()).toBe(true)
    // The real transaction committed, but the browser receives an unusable response.
    await route.fulfill({ status: 400, json: { message: 'Response lost' } })
  })
  await confirm(page, page.getByRole('button', { name: 'Verify payment', exact: true }))
  await expect(page.getByRole('alert')).toContainText('Could not complete')
  expect((await f.admin.from('booking_payments').select('status').eq('booking_id', f.bookings[0].id).single()).data.status).toBe('paid')
  await page.unroute('**/rpc/admin_verify_bank_transfer')
  await confirm(page, page.getByRole('button', { name: 'Verify payment', exact: true }))
  await expect(page.getByRole('dialog').getByText('Confirmed · Paid', { exact: true })).toBeVisible()
  expect(keys).toHaveLength(2); expect(keys[0]).toBe(keys[1])
  expect((await f.admin.from('command_requests').select('id').eq('scope', `admin-payment:${f.user.id}`)).data).toHaveLength(1)
  expect((await f.admin.from('event_outbox').select('id').eq('aggregate_id', f.bookings[0].id)).data).toHaveLength(1)
})

