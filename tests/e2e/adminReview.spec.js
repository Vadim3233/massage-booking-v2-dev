test('an older manual refresh cannot overwrite status fetched after a payment action', async ({ page }) => {
  await f.authorize(); await login(page, `/admin/bookings/${f.bookings[0].id}`)
  await expect(page.getByRole('button', { name: 'Verify payment', exact: true })).toBeVisible()
  let release, captured
  const gate = new Promise(resolve => { release = resolve })
  const ready = new Promise(resolve => { captured = resolve })
  let reads = 0
  await page.route('**/rest/v1/bookings?**', async route => {
    if (++reads !== 1) return route.continue()
    const response = await route.fetch(); captured(); await gate
    await route.fulfill({ response })
  })
  await page.getByRole('button', { name: 'Refresh booking', exact: true }).click()
  await ready
  await confirm(page, page.getByRole('button', { name: 'Verify payment', exact: true }))
  await expect(page.getByRole('dialog').getByText('Confirmed · Paid', { exact: true })).toBeVisible()
  const oldRead = page.waitForResponse(r => r.url().includes('/rest/v1/bookings?'))
  release(); await (await oldRead).finished()
  await page.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))))
  await expect(page.getByRole('dialog').getByText('Confirmed · Paid', { exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Verify payment', exact: true })).toHaveCount(0)
})
