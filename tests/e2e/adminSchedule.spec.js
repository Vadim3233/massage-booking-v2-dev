test('a holiday over several days, starting and ending part-way through a day, is one block that can be changed and removed', async ({ page }) => {
  await f.authorize()
  const day = offset => new Date(Date.now() + offset * 86400000).toISOString().slice(0, 10)
  const first = day(120), last = day(122)
  await signIn(page, '/admin/schedule')
  await page.getByRole('tab', { name: 'Special days' }).click()
  await page.getByRole('button', { name: 'Block time', exact: true }).click()
  const dialog = page.locator('dialog.admin-action')
  await dialog.getByLabel('Label (optional)').fill('Summer break')
  await dialog.getByLabel('Start date').fill(first)
  await expect(dialog.getByLabel('End date')).toHaveValue(first)
  await dialog.getByLabel('End date').fill(last)
  await dialog.getByLabel('Start time').selectOption('840')
  await dialog.getByLabel('End time').selectOption('600')
  await expect(dialog.getByRole('status')).toContainText('3 days')
  expect(await dialog.evaluate(el => el.scrollWidth <= el.clientWidth)).toBe(true)
  await dialog.getByRole('button', { name: 'Block this time' }).click()
  const item = page.locator('.admin-blocked-time li', { hasText: 'Summer break' })
  await expect(item).toContainText(' to ')
  const rows = (await f.admin.from('calendar_blocks').select('date,start_minutes,end_minutes').eq('title', 'Summer break').order('date')).data
  expect(rows).toEqual([{ date: first, start_minutes: 840, end_minutes: 1440 }, { date: day(121), start_minutes: 0, end_minutes: 1440 }, { date: last, start_minutes: 0, end_minutes: 600 }])

  await item.getByRole('button', { name: 'Change' }).click()
  await expect(dialog.getByRole('heading', { name: 'Change blocked time' })).toBeVisible()
  await expect(dialog.getByLabel('End date')).toHaveValue(last)
  await dialog.getByLabel('End date').fill(day(121))
  await dialog.getByRole('button', { name: 'Save changes' }).click()
  await expect(dialog).toHaveCount(0)
  expect((await f.admin.from('calendar_blocks').select('id').eq('title', 'Summer break')).data).toHaveLength(2)

  await item.getByRole('button', { name: 'Change' }).click()
  await dialog.getByRole('button', { name: 'Remove', exact: true }).click()
  await expect(dialog).toContainText('all 2 days')
  await dialog.getByRole('button', { name: 'Yes, remove' }).click()
  await expect(page.locator('.admin-blocked-time li', { hasText: 'Summer break' })).toHaveCount(0)
  expect((await f.admin.from('calendar_blocks').select('id').eq('title', 'Summer break')).data).toHaveLength(0)
})
